// Composes a deployable wrangler config from the tracked defaults plus one
// selected target. Targets are wrangler config fragments: a named profile from
// deploy-profiles.jsonc, or the local setup state. The runtime settings always
// come from wrangler.base.jsonc, so limits and the entry point are never
// maintained in two places.

import fs from "node:fs";
import path from "node:path";
import { parseJsonc } from "./jsonc.mjs";
import { baseConfigPath, generatedConfigPath, localDir, profilesPath } from "./paths.mjs";

/** Keys a target fragment may set. Anything else is a typo we refuse to deploy. */
const FRAGMENT_KEYS = new Set([
  "description",
  "name",
  "account_id",
  "workers_dev",
  "preview_urls",
  "routes",
  "vars",
]);

export function readBaseConfig(file = baseConfigPath) {
  return parseJsonc(fs.readFileSync(file, "utf8"), path.basename(file));
}

export function readProfiles(file = profilesPath) {
  if (!fs.existsSync(file)) return {};
  return parseJsonc(fs.readFileSync(file, "utf8"), path.basename(file));
}

/** The target fragment for a named profile, or null when it does not exist. */
export function profileFragment(name, profiles) {
  const fragment = profiles[name];
  if (!fragment) return null;
  return { label: name, ...fragment };
}

/** The target fragment for a completed `npm run setup`, or null. */
export function stateFragment(state) {
  if (!state?.workerName || !state?.accountId) return null;
  const vars = {};
  if (state.allowedMailboxes) vars.ALLOWED_MAILBOXES = state.allowedMailboxes;
  // Present (including as "") means the owner made an explicit choice; absent
  // inherits the tracked default.
  if (typeof state.allowedCalendars === "string") vars.ALLOWED_CALENDARS = state.allowedCalendars;
  return {
    label: "local",
    description: `guided setup (${state.workerName} in account ${state.accountId})`,
    name: state.workerName,
    account_id: state.accountId,
    workers_dev: true,
    ...(Object.keys(vars).length > 0 ? { vars } : {}),
  };
}

/**
 * Merge a target fragment over the tracked defaults. `vars` is merged key by
 * key so a target can override one limit; everything else replaces.
 * Relative paths in the base config are rewritten for `configDir`, which is
 * not the repo root.
 */
export function composeConfig(base, fragment, configDir) {
  const { label, description, ...overrides } = fragment;
  for (const key of Object.keys(overrides)) {
    if (!FRAGMENT_KEYS.has(key)) {
      throw new Error(
        `deployment target "${label}" sets unsupported key "${key}"; allowed: ${[...FRAGMENT_KEYS].join(", ")}`,
      );
    }
  }
  if (!overrides.name) throw new Error(`deployment target "${label}" is missing a Worker name`);

  const config = { ...base, ...overrides };
  config.vars = { ...base.vars, ...overrides.vars };
  for (const key of ["$schema", "main"]) {
    const value = base[key];
    if (typeof value === "string" && !path.isAbsolute(value)) {
      config[key] = path.relative(configDir, path.resolve(path.dirname(baseConfigPath), value));
    }
  }
  return config;
}

/** Write the composed config for a target and return its path. */
export function writeGeneratedConfig(fragment, { base = readBaseConfig(), dir = localDir } = {}) {
  const file = generatedConfigPath(fragment.label, dir);
  const config = composeConfig(base, fragment, dir);
  const header = [
    "// Generated by scripts/deploy.mjs — do not edit, it is rewritten on every",
    `// deploy. Target: ${fragment.label}${fragment.description ? ` (${fragment.description})` : ""}.`,
    "// Change wrangler.base.jsonc, deploy-profiles.jsonc, or re-run npm run setup.",
  ].join("\n");
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(file, `${header}\n${JSON.stringify(config, null, 2)}\n`, { mode: 0o644 });
  return file;
}
